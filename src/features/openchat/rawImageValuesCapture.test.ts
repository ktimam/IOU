import { createHash } from "node:crypto";
import { describe, expect, it } from "vitest";
import captures from "./fixtures/gemma-values-r3-synthetic-20261005.json";
import { gradeExactRawImageFacts } from "./rawImageFactualGrade";
import { normalizeRawImageValuesRow } from "./rawImageValuesRow";
import { processLocalArtifactRequest } from "./localProcessorArtifact";
import { iouImageProcessorOptions } from "./modelImageProfiles";

const options = { rawImageMoneyFormat: "total-row", rawImageDetailsFormat: "direction-v1", rawImageValuesRowFormat: "split-six-v1" } as const;
const captured = (id: string) => {
  const capture = captures.captures.find(item => item.id === id);
  if (!capture) throw new Error("Missing synthetic capture");
  return capture;
};
const process = (rows: unknown[], selected = options) => processLocalArtifactRequest({
  type: "oc:local-process:request", version: 1, actionId: "iou.entry.import",
  input: { operation: "normalize_raw", modality: "image", candidates: rows, sourceTimestamp: Date.parse("2026-09-27T12:00:00Z") },
}, selected);

describe("retained synthetic R3 values-row model evidence", () => {
  it.each(captures.captures)("keeps exact source bytes and framing for $id", capture => {
    expect(Buffer.byteLength(capture.rawText)).toBe(capture.rawBytes);
    expect(createHash("sha256").update(capture.rawText).digest("hex")).toBe(capture.rawSha256);
    expect(captures).toMatchObject({ maxTokens: 96, productionExactWorker: true, cleanupConfirmed: true, fullCacheShaReverified: true, candidateActivated: false });
  });

  it("grades two row-local transactions before normalization, then preserves indexes and every field", () => {
    // Expected values were frozen in the prospective oracle before inference;
    // they are source expectations, not generated by the model or decoder.
    const expected = [
      { values: ["Invoice A", "USD", "12.34", "1 October 2026", "iou", "You owe"] },
      { values: ["Invoice B", "EUR", "56.78", "2 October 2026", "iou", "Owed to you"] },
    ];
    const raw = captured("two-invoices-both-directions").rawText;
    expect(gradeExactRawImageFacts(raw, expected)).toEqual({ passed: true, issues: [] });
    const rows = JSON.parse(raw), before = JSON.stringify(rows);
    expect(process(rows)).toEqual({ kind: "candidates", sourceIndexes: [0, 1], candidates: [
      { amount: 12.34, currency: "USD", kind: "iou", direction: "debt", date: "2026-10-01", note: "Invoice A" },
      { amount: 56.78, currency: "EUR", kind: "iou", direction: "credit", date: "2026-10-02", note: "Invoice B" },
    ] });
    expect(JSON.stringify(rows)).toBe(before);
    expect(gradeExactRawImageFacts(JSON.stringify(rows.slice(0, 1)), expected).passed).toBe(false);
    const crossed = structuredClone(rows); crossed[0].values[3] = rows[1].values[3];
    expect(gradeExactRawImageFacts(JSON.stringify(crossed), expected)).toEqual({ passed: false, issues: ["$[0].values[3]:value"] });
  });

  it("does not present the editable credit default as printed image evidence", () => {
    const raw = captured("absent-direction-no-date-unmatched").rawText;
    expect(gradeExactRawImageFacts(raw, [{ values: ["Service invoice", "EUR", "42.75", "", "iou", ""] }])).toEqual({ passed: true, issues: [] });
    const rows = JSON.parse(raw), evidence = normalizeRawImageValuesRow(rows[0]);
    expect(evidence).not.toHaveProperty("direction"); expect(evidence).not.toHaveProperty("printed_date");
    expect(process(rows)).toEqual({ kind: "candidates", sourceIndexes: [0], candidates: [
      { amount: 42.75, currency: "EUR", kind: "iou", direction: "credit", note: "Service invoice" },
    ] });
  });

  it("retains the printed-debt grammar failure even though its repeated units describe the right money", () => {
    const raw = captured("printed-debt-format-failure").rawText;
    const expected = [{ values: ["SYNTHETIC TEST INVOICE", "USD", "123.45", "27 September 2026", "iou", "You owe"] }];
    expect(gradeExactRawImageFacts(raw, expected)).toEqual({ passed: false, issues: ["$[0].values[2]:value"] });
    const rows = JSON.parse(raw); // Complete JSON is not this contract's acceptance.
    expect(normalizeRawImageValuesRow(rows[0])).toBeUndefined();
    expect(process(rows)).toEqual({ kind: "error" });
  });

  it("does not activate the opt-in in current packaged model options", () => {
    expect(iouImageProcessorOptions).toEqual({ rawImageMoneyFormat: "total-row" });
    expect(processLocalArtifactRequest({ type: "oc:local-process:request", version: 1, actionId: "iou.entry.import",
      input: { operation: "normalize_raw", modality: "image", candidates: JSON.parse(captured("two-invoices-both-directions").rawText) },
    }, iouImageProcessorOptions)).toEqual({ kind: "error" });
  });
});
